        CREATE POLICY "Users can manage their own routines" ON routines FOR ALL USING (auth.uid() = user_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Users can manage their own routine logs') THEN
        CREATE POLICY "Users can manage their own routine logs" ON routine_logs FOR ALL USING (auth.uid() = user_id);
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_policies WHERE policyname = 'Users can manage their own AI timetables') THEN
        CREATE POLICY "Users can manage their own AI timetables" ON ai_timetables FOR ALL USING (auth.uid() = user_id);
    END IF;
